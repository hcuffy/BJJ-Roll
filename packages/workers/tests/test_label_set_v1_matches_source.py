def test_label_set_details_match_source_in_order_with_labels_and_gi_flags() -> None:
    label_set = load_label_set()
    got = {label.id: tuple((d.id, d.label, d.gi_only) for d in label.details) for label in label_set.positions + label_set.events}
    assert tuple(got) == tuple(SOURCE_DETAILS)
    for class_id, expected in SOURCE_DETAILS.items():
        assert got[class_id] == expected, class_id
